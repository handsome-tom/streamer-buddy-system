def path(grid):
    out=[]
    for y,row in enumerate(grid.strip("\n").split("\n")):
        x=0
        while x<len(row):
            if row[x]=="#":
                s=x
                while x<len(row) and row[x]=="#": x+=1
                out.append(f"M{s} {y}h{x-s}v1h-{x-s}z")
            else: x+=1
    return "".join(out)
